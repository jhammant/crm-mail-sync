"""Small interfaces for offline and live services."""
from datetime import datetime
from typing import Protocol
from collections.abc import Iterable
from ..models import Associations, Contact, Deal, Message


class MailSource(Protocol):
    def fetch(self, since: datetime) -> Iterable[Message]: ...
    def get(self, message_id: str) -> Message: ...


class Crm(Protocol):
    def contact_by_email(self, email: str) -> Contact | None: ...
    def deals_for_contact(self, contact_id: str) -> list[Deal]: ...
    def email_exists(self, message: Message) -> bool: ...
    def create_email(self, message: Message, associations: Associations, direction: str) -> str: ...


class ReviewSink(Protocol):
    def enqueue(self, message: Message, reason: str) -> None: ...
    def pending(self) -> dict[str, dict]: ...
    def resolve(self, message_id: str, action: str) -> None: ...
