"""Small structural interfaces for alternative integrations."""
from collections.abc import Iterable, Mapping, Sequence
from datetime import datetime
from typing import Protocol

from ..models import Associations, Contact, Deal, Message


class MailSource(Protocol):
    def messages(self, since: datetime) -> Iterable[Message]: ...
    def get_message(self, message_id: str) -> Message: ...


class Crm(Protocol):
    def contact(self, email: str) -> Contact | None: ...
    def deals(self, contact_id: str) -> Sequence[Deal]: ...
    def existing_email(self, message: Message) -> bool: ...
    def create_email(self, message: Message, associations: Associations, direction: str) -> str: ...


class ReviewSink(Protocol):
    def pending(self) -> Mapping[str, dict]: ...
    def enqueue(self, message: Message, reason: str) -> None: ...
    def resolve(self, message_id: str, action: str) -> None: ...
